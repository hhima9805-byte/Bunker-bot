# Катастрофы базового набора, которые относятся к фантастике
FANTASY_IN_BASE = {"Восстание искусственного интеллекта", "Инопланетное вторжение", "Споры мутировавшего грибка"}

PACK_NAMES = {
    "realism": "Реализм",
    "fantasy": "Фантастика",
    "absurd": "Абсурд",
    "mixed": "Смешанный",
}
PACK_ORDER = ["realism", "fantasy", "absurd", "mixed"]

_TRAIT_LISTS = {
    "profession": ("PROFESSIONS", "FANTASY_PROFESSIONS", "ABSURD_PROFESSIONS"),
    "health": ("HEALTH", "FANTASY_HEALTH", "ABSURD_HEALTH"),
    "hobby": ("HOBBIES", "FANTASY_HOBBIES", "ABSURD_HOBBIES"),
    "baggage": ("BAGGAGE", "FANTASY_BAGGAGE", "ABSURD_BAGGAGE"),
    "fact": ("FACTS", "FANTASY_FACTS", "ABSURD_FACTS"),
}


def trait_pools(pack, key):
    """(основной список, особый список набора) для характеристики. Особый список может быть пустым."""
    g = globals()
    if key not in _TRAIT_LISTS:
        return {"phobia": PHOBIAS, "character": CHARACTERS}[key], []
    base_name, fantasy_name, absurd_name = _TRAIT_LISTS[key]
    base = g[base_name]
    if pack == "fantasy":
        return base, g[fantasy_name]
    if pack == "absurd":
        return base, g[absurd_name]
    if pack == "mixed":
        return base + g[fantasy_name] + g[absurd_name], []
    return base, []


def scenario_pools(pack):
    """(катастрофы, бункеры) для набора"""
    realistic = [c for c in CATASTROPHES if c["name"] not in FANTASY_IN_BASE]
    fantasy = [c for c in CATASTROPHES if c["name"] in FANTASY_IN_BASE] + FANTASY_CATASTROPHES
    if pack == "fantasy":
        return fantasy, BUNKERS + FANTASY_BUNKERS
    if pack == "absurd":
        return ABSURD_CATASTROPHES, ABSURD_BUNKERS + BUNKERS
    if pack == "mixed":
        return realistic + fantasy + ABSURD_CATASTROPHES, BUNKERS + FANTASY_BUNKERS + ABSURD_BUNKERS
    return realistic, BUNKERS
